def worked_examples(
    data, out_dir, prefix, doc_ids, top_k=7, exclude=DUMB_DESC, label=None
) -> list[str]:
  """Layout-A tables of the chosen documents of one analyze JSON.

  Writes `<prefix>_macros.tex`, `<prefix>_A_<label><k>_<id>.tex` per document
  in `doc_ids` order and `preview_<prefix>.tex` (standalone, ACL text block);
  contributions that would print as 0.00 are dropped first. Returns the paths.
  """
  docs = {}
  for pair in data["pairs"]:
    for doc in pair["docs"]:
      doc["features"] = [f for f in doc["features"] if abs(f["cf"]) >= 0.005]
      doc["n_active"] = len(doc["features"])
      docs[doc["id"]] = doc
  exclude_re = re.compile(exclude, re.I) if exclude else None
  written, bodies = [], []

  def emit(name, body):
    written.append(write(os.path.join(out_dir, name), body))
    bodies.append(body)
    return written[-1]

  paths = [emit(f"{prefix}_macros.tex", WORKED_MACROS)]
  for k, doc_id in enumerate(doc_ids, 1):
    doc = docs[doc_id]
    coverage(doc, top_k, exclude_re)
    body = worked_example_table(doc, data["meta"], top_k, exclude_re, label)
    emit(f"{prefix}_A_{doc['label']}{k}_{doc_id}.tex", body)
  preview = "\n".join(
      [
          r"\documentclass[11pt,twocolumn]{article}",
          r"\usepackage[letterpaper,textwidth=16cm,textheight=22.9cm]{geometry}",
          r"\usepackage{booktabs}",
          r"\usepackage{xcolor}",
          r"\usepackage[T1]{fontenc}",
          r"\usepackage{textcomp}",
          bodies[0],
          r"\begin{document}",
          "\n\\clearpage\n".join(bodies[1:]),
          r"\end{document}",
          "",
      ]
  )
  emit(f"preview_{prefix}.tex", preview)
  return (
      [os.path.join(out_dir, f"{prefix}_macros.tex")]
      + [
          os.path.join(out_dir, f"{prefix}_A_{docs[d]['label']}{k}_{d}.tex")
          for k, d in enumerate(doc_ids, 1)
      ]
      + [os.path.join(out_dir, f"preview_{prefix}.tex")]
  )


