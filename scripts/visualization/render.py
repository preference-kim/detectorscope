# tab:datasets from the per-split summary frame (dataset, split, n, n_gen,
# generators, domains).
def generator_cell(g) -> str:
  """Families in descending AI-doc order; '(k)' counts a family's generators."""
  fam = (
      g.groupby("family")
      .agg(n=("n", "sum"), k=("canonical", "nunique"))
      .sort_values("n", ascending=False)
  )
  return ", ".join(
      f"{tex(f)} ({r.k})" if r.k > 1 else tex(f) for f, r in fam.iterrows()
  )


def domain_cell(d) -> str:
  """Domain groups in descending doc order (authored as LaTeX already)."""
  grp = d.groupby("domain_group")["n"].sum().sort_values(ascending=False)
  return ", ".join(grp.index)


