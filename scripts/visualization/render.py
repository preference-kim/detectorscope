def listable(doc, exclude_re):
  """Features eligible for the list column; excluded ones fold into 'more'."""
  return [
      f
      for f in doc["features"]
      if not (exclude_re and exclude_re.search(f.get("terse") or ""))
  ]


def pick(doc, top_k, exclude_re=None):
  """Top-k features per side by |cf| as (ai, human), tagged with side and key."""
  cand = listable(doc, exclude_re)
  ai = sorted((f for f in cand if f["cf"] > 0), key=lambda f: -f["cf"])[:top_k]
  hu = sorted((f for f in cand if f["cf"] < 0), key=lambda f: f["cf"])[:top_k]
  for i, f in enumerate(ai):
    f.update(side="ai", key=AI_KEYS[i])
  for i, f in enumerate(hu):
    f.update(side="hu", key=HU_KEYS[i])
  return ai, hu


def coverage(doc, top_k, exclude_re) -> None:
  """Record on the doc the |contribution| share of its listed features."""
  ai, hu = pick(doc, top_k, exclude_re)
  total = sum(abs(f["cf"]) for f in doc["features"])
  listed = sum(abs(f["cf"]) for f in ai + hu)
  doc["coverage"] = listed / total if total else 0.0


def token_strength(tokens, listed):
  """Per token, the largest |w_i a_it| over the listed features firing on it.

  With max-pooling w_i = cf_i / max_t a_it, so the feature's peak token
  carries its full listed contribution.
  """
  strength = [0.0] * len(tokens)
  for f in listed:
    peak = max(f.get("token_act") or [0]) or 1.0
    for i, a in zip(f["token_idx"], f.get("token_act") or []):
      if i < len(tokens):
        strength[i] = max(strength[i], abs(f["cf"]) * a / peak)
  return strength


def shade_level(strength, top) -> int:
  """Shade level 1-3 from strength / top via SHADE_CUTS."""
  if top <= 0:
    return 2
  r = strength / top
  return 3 if r >= SHADE_CUTS[1] else 2 if r >= SHADE_CUTS[0] else 1


def ws(s) -> str:
  """Whitespace run -> LaTeX: a space, a line break or a paragraph break."""
  if "\n" not in s:
    return " " if s else ""
  return r"\newline " if s.count("\n") == 1 else r"\newline\mbox{}\newline "


def glyph(tok) -> str:
  """Visible stand-in for a highlighted whitespace-only / BOS token."""
  if tok == "":
    return r"$\langle$bos$\rangle$"
  return r"$\hookleftarrow$" if "\n" in tok else r"\textvisiblespace"


def box(feat, body, level) -> str:
  macro = r"\hlai[%d]{%s}" if feat["side"] == "ai" else r"\hlhu[%d]{%s}"
  return macro % (level, body)


def render_text(tokens, listed) -> str:
  """Typeset `tokens` with runs of listed-feature tokens boxed and keyed.

  Sub-word tokens of one word with the same feature set share a box; the key
  superscript is attached once at the end of a run; the empty BOS token is
  never shaded. Trailing line breaks are stripped.
  """
  active = [[] for _ in tokens]
  for f in listed:
    for i in f["token_idx"]:
      if i < len(tokens) and tokens[i] != "":
        active[i].append(f)
  strength = token_strength(tokens, listed)
  top = max((strength[i] for i in range(len(tokens)) if active[i]), default=0.0)
  out, quotes = [], 0
  pending = None  # open box: [strongest feature, key set, text, level]
  glue = False  # the previous token ended without whitespace

  def flush():
    nonlocal pending
    if pending:
      out.append(box(pending[0], pending[2], pending[3]))
      pending = None

  for i, tok in enumerate(tokens):
    feats = active[i]
    core = tok.strip()
    lead, trail = (
        (tok[: len(tok) - len(tok.lstrip())], tok[len(tok.rstrip()) :])
        if core
        else ("", tok)
    )
    body = tex_text(core) if core else (glyph(tok) if feats else "")
    if body.startswith("'") and (len(body) > 1 or lead or i == 0):
      body = "`" + body[1:]
    while '"' in body:
      body = body.replace('"', "``" if quotes % 2 == 0 else "''", 1)
      quotes += 1
    keyset = {f["key"] for f in feats}
    if feats:
      level = shade_level(strength[i], top)
      if pending and glue and not lead and pending[1] == keyset:
        pending[2] += body
        pending[3] = max(pending[3], level)
      else:
        flush()
        out.append(ws(lead))
        pending = [max(feats, key=lambda f: abs(f["cf"])), keyset, body, level]
      nxt = {f["key"] for f in active[i + 1]} if i + 1 < len(tokens) else set()
      if nxt != keyset:
        flush()
        out.append(r"\fk{%s}" % ",".join(sorted(keyset)))
      elif trail:
        flush()
    else:
      flush()
      out += [ws(lead), body]
    out.append(ws(trail))
    glue = not trail and bool(core)
  flush()
  s = "".join(out).strip()
  return re.sub(r"(\\newline(\\mbox\{\})?\s*)+$", "", s)


def evidence_lines(doc, ai, hu) -> str:
  """Feature-list cell: listed features per side plus a '+ N more' line."""
  lines = []
  for title, sel, side in (
      (r"\textit{Toward AI}", ai, 1),
      (r"\textit{Toward human}", hu, -1),
  ):
    rest = [f for f in doc["features"] if f["cf"] * side > 0 and f not in sel]
    if not sel and not rest:
      continue
    lines.append(title + r"\newline")
    for f in sel:
      desc = paper.description_cell(f, keywords=False, escape=tex_text)
      lines.append(f"\\fk{{{f['key']}}}\\,{num(f['cf'])}\; {desc}\\newline")
    if rest:
      lines.append(
          r"\textit{+ %d more}\; %s\newline"
          % (len(rest), num(sum(f["cf"] for f in rest)))
      )
  return (
      "\n".join(lines).rstrip(r"\newline")
      if lines
      else r"\textit{no active features}"
  )


def score_cell(doc) -> str:
  """Score column as a nested tabular: sums per side, bias, logit, P(AI)."""
  s_ai = sum(f["cf"] for f in doc["features"] if f["cf"] > 0)
  s_hu = sum(f["cf"] for f in doc["features"] if f["cf"] < 0)
  verdict = "AI" if doc["logit"] > 0 else "Human"
  return "\n".join(
      [
          r"\begin{tabular}[t]{@{}lr@{}}",
          r"$\Sigma$ AI    & %s \\" % num(s_ai),
          r"$\Sigma$ human & %s \\" % num(s_hu),
          r"bias           & %s \\" % num(doc["bias"]),
          r"\midrule",
          r"logit          & %s \\" % num(doc["logit"]),
          r"$P(\mathrm{AI})$ & $%d\%%$ \\" % round(100 * doc["prob"]),
          r"\multicolumn{2}{@{}l}{\textbf{$\rightarrow$ %s}} \\" % verdict,
          r"\end{tabular}",
      ]
  )


