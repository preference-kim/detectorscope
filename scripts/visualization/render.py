def md_table(d) -> str:
  """Markdown table of `d` (floats to three decimals)."""

  def fmt(v):
    return f"{v:.3f}" if isinstance(v, float) else str(v)

  rows = ["| " + " | ".join(d.columns) + " |", "|" + "---|" * len(d.columns)]
  rows += [
      "| " + " | ".join(fmt(v) for v in r) + " |"
      for r in d.itertuples(index=False)
  ]
  return "\n".join(rows)


def top10_tables(heads: dict, out_dir) -> str:
  """top10_tau0.85.{tex,md} and all_features_tau0.85.csv of the PRDB heads.

  `heads` maps gpt4o / llama to the LOR-joined feature frame of that
  FT-Model+SAE head. The .tex holds one block per table (a `% name` comment,
  body rows and a closing `\\midrule`) for pasting into the paper's tabular;
  the .md adds the long descriptions and is returned.
  """
  frames = {}
  for target, df in heads.items():
    df = df.rename(
        columns={"terse": "description.terse", "long": "description.long"}
    )
    frames[target] = df.assign(head=target)[MAIN_COLS]
  both = pd.concat([frames["gpt4o"], frames["llama"]])
  os.makedirs(out_dir, exist_ok=True)
  both.to_csv(f"{out_dir}/all_features_tau{TAU}.csv", index=False)
  tables = {
      "GPT-4o (gpt4o head, AI-direction)": top_rows(
          frames["gpt4o"], +1, N_MAIN
      ),
      "Llama (llama head, AI-direction)": top_rows(frames["llama"], +1, N_MAIN),
      "Human (pooled gpt4o+llama heads, human-direction)": top_rows(
          both, -1, N_MAIN
      ),
  }
  md, body = [], []
  for name, d in tables.items():
    md.append(f"\n### {name}\n\n" + md_table(d[TOP10_COLS]) + "\n")
    md.append(
        "\nLong descriptions:\n\n"
        + "\n".join(
            f"- **{r.feat}** ({r['head']}): {r['description.long']}"
            for _, r in d.iterrows()
        )
        + "\n"
    )
    body.append(f"% {name}\n")
    for _, r in d.iterrows():
      body.append(
          f"  & {tex(r.feat)} & {tex(r['description.terse'])} & {r['corr']:.3f} & {r.mean_cf:+.3f} & ${r.lor:.3f}$ & {int(r.human_density):,} & {int(r.target_density):,} \\\\\n"
      )
    body.append("\\midrule\n")
  write(f"{out_dir}/top10_tau{TAU}.tex", "".join(body))
  return write(f"{out_dir}/top10_tau{TAU}.md", "".join(md))


