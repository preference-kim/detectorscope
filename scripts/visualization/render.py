def write(path, text) -> str:
  """Write `text` to `path` (creating its directory) and return the text."""
  if path:
    os.makedirs(os.path.dirname(str(path)) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
      f.write(text)
  return text


def pct(x: float) -> str:
  """x100 at one decimal; a rounded 100.0 prints as 100, as in the paper."""
  s = f"{x * 100:.1f}"
  return "100" if s == "100.0" else s


def num(v) -> str:
  """Signed two-decimal number in math mode."""
  return f"${v:+.2f}$"


def sig(x: float, n: int = 3) -> str:
  """Signed fixed-point string, n significant figures, trailing zeros kept."""
  if x == 0 or not np.isfinite(x):
    return f"{x:+.{n - 1}f}"
  decimals = max(0, n - 1 - int(np.floor(np.log10(abs(x)))))
  return f"{x:+.{decimals}f}"


def row(label: str, cells: list[str]) -> str:
  return " & ".join([label] + cells) + r" \\"


