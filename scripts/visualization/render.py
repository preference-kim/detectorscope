def sae_rows(head: str) -> list[tuple[str, str]]:
  """(row label, eval dir) of the three SAE conditions for one head type."""
  return [(SAE_TEX[sae], paper.eval_dir(sae, head)) for sae in SAE_ORDER]


def lookup(df, dataset, split, model, target, tau=None) -> pd.Series:
  """The one result row of a detector; tau None takes the untuned file."""
  d = df[
      (df["dataset"] == dataset)
      & (df["split"] == split)
      & (df["model"] == model)
      & (df["target"] == target)
  ]
  if tau is None:
    d = d[d["threshold"].isna() | (d["threshold"] == 0.0)]
  else:
    d = d[np.isclose(d["threshold"].fillna(-1.0), tau)]
  if len(d) != 1:
    raise LookupError(
        f"{dataset}_{split}/{model} target={target} tau={tau}: {len(d)} rows"
    )
  return d.iloc[0]


def group_header(groups: list[str], per_group: int) -> list[str]:
  """The two header lines: bold group titles and their cmidrules."""
  titles = " & ".join(
      rf"\multicolumn{{{per_group}}}{{c}}{{\textbf{{{g}}}}}" for g in groups
  )
  rules = " ".join(
      rf"\cmidrule(lr){{{2 + per_group * i}-{1 + per_group * (i + 1)}}}"
      for i in range(len(groups))
  )
  return [f"& {titles} " + r"\\", rules]


def section(title: str, n_cols: int) -> str:
  return rf"\multicolumn{{{n_cols}}}{{l}}{{\textbf{{{title}}}}} \\"


def wrap(body, n_cols, env, size, colsep, caption, label) -> str:
  """The table environment around a finished tabular body."""
  lines = [
      rf"\begin{{{env}}}[t]",
      r"\centering",
      size,
      rf"\setlength{{\tabcolsep}}{{{colsep}}}",
      rf"\begin{{tabular}}{{l{'c' * (n_cols - 1)}}}",
      r"\toprule",
      *body,
      r"\bottomrule",
      r"\end{tabular}",
      rf"\caption{{{caption}}}",
      rf"\label{{{label}}}",
      rf"\end{{{env}}}",
  ]
  return "\n".join(lines) + "\n"


def head_sections(df, head, cols, metrics, neural_label="hf-gemma2"):
  """Baselines / w/o Mask / w/ Mask rows as (label, values) over cols.

  cols is a list of (dataset, split, target) column groups; values are the
  unrounded metrics in column order.
  """

  def values(model, tau):
    return [
        lookup(df, ds, sp, model, tg, tau)[m]
        for ds, sp, tg in cols
        for m in metrics
    ]

  return [
      (
          "Baselines",
          [
              ("gram2vec", values(LINGUISTIC[head], None)),
              (neural_label, values("hf_gemma2", None)),
          ],
      ),
      ("w/o Mask", [(lab, values(m, 0.0)) for lab, m in sae_rows(head)]),
      (
          r"w/ Mask ($\tau\!>\!0.7$)",
          [(lab, values(m, paper.MASK_TAU)) for lab, m in sae_rows(head)],
      ),
  ]


def dagger_rows(df, cols, metrics, order, split="gpt4o"):
  """Off-the-shelf rows; on PRDB every target is read from one split dir."""
  return [
      (
          DAGGER[model],
          [
              lookup(df, ds, split if ds == "PRDB" else sp, model, tg)[m]
              for ds, sp, tg in cols
              for m in metrics
          ],
      )
      for model in order
  ]


def coling_results(df, head="logreg", path=None) -> str:
  """tab:results: COLING dev/devtest/test + RAID test, column max in bold."""
  cols = [("COLING", s, "all") for s in ("dev", "devtest", "test")]
  cols.append(("RAID", "test", "all"))
  metrics = ["auroc", "f1", "recall_at_5_fpr"]
  groups = ["COLING (dev)", "COLING (devtest)", "COLING (test)", "RAID (test)"]
  sections = [(None, dagger_rows(df, cols, metrics, COLING_DAGGER))]
  sections += head_sections(df, head, cols, metrics, "gemma-2-2b")
  sections[-1] = (r"w/ Mask ($\tau>0.7$)", sections[-1][1])
  n_cols = 1 + len(cols) * len(metrics)
  all_values = np.array([v for _, rows in sections for _, v in rows])
  best = all_values.argmax(axis=0)
  body = group_header(groups, len(metrics))
  body.append(row("", [NA_METRICS[m] for m in metrics] * len(cols)))
  base_row = 0
  for title, rows in sections:
    body.append(r"\midrule")
    if title:
      body.append(section(title, n_cols))
    for r, (label, vals) in enumerate(rows):
      cells = [
          rf"\textbf{{{pct(v)}}}" if best[j] == base_row + r else pct(v)
          for j, v in enumerate(vals)
      ]
      body.append(row(label, cells))
    base_row += len(rows)
  return write(
      path,
      wrap(
          body,
          n_cols,
          "table*",
          r"\small",
          "5pt",
          CAPTIONS["coling"],
          "tab:results",
      ),
  )


def prdb_indomain(df, head="logreg", path=None) -> str:
  """tab:prdb_results_indomain: each head on the generator it was trained on."""
  metrics = ["auroc", "f1", "recall_at_1_fpr"]
  cols = [("PRDB", "gpt4o", "gpt4o"), ("PRDB", "llama", "llama")]
  groups = [paper.GENERATOR_LABEL[t] for _, _, t in cols]
  n_cols = 1 + len(cols) * len(metrics)
  sections = [(None, dagger_rows(df, cols, metrics, PRDB_DAGGER))]
  sections += head_sections(df, head, cols, metrics)
  body = group_header(groups, len(metrics))
  body.append(row("", ["AUC", "F1", "TPR@1"] * len(cols)))
  for title, rows in sections:
    body.append(r"\midrule")
    if title:
      body.append(section(title, n_cols))
    for label, vals in rows:
      body.append(row(label, [pct(v) for v in vals]))
  return write(
      path,
      wrap(
          body,
          n_cols,
          "table",
          r"\footnotesize",
          "1.6pt",
          CAPTIONS["prdb_indomain"],
          "tab:prdb_results_indomain",
      ),
  )


def prdb_full(df, head="logreg", path=None) -> str:
  """tab:prdb_results_full: GPT-4o- and Llama-trained heads on all targets."""
  metrics = ["auroc", "f1", "recall_at_5_fpr"]
  targets = list(paper.GENERATOR_LABEL)
  n_cols = 1 + len(targets) * len(metrics)
  body = group_header(list(paper.GENERATOR_LABEL.values()), len(metrics))
  body.append(row("", [NA_METRICS[m] for m in metrics] * len(targets)))
  for i, (split, name) in enumerate([("gpt4o", "GPT-4o"), ("llama", "LLaMA")]):
    cols = [("PRDB", split, t) for t in targets]
    body.append(
        r"\midrule" if i == 0 else r"\specialrule{\heavyrulewidth}{3pt}{3pt}"
    )
    body.append(
        rf"\multicolumn{{{n_cols}}}{{l}}{{\textit{{Trained on {name}}}}} \\[2pt]"
    )
    for j, (title, rows) in enumerate(head_sections(df, head, cols, metrics)):
      if j:
        body.append(r"\midrule")
      body.append(section(title, n_cols))
      for label, vals in rows:
        body.append(row(label, [pct(v) for v in vals]))
  body.append(r"\midrule")
  body.append(
      rf"\multicolumn{{{n_cols}}}{{l}}{{\textit{{Off-the-shelf}}}} \\[2pt]"
  )
  cols = [("PRDB", "gpt4o", t) for t in targets]
  for label, vals in dagger_rows(df, cols, metrics, PRDB_DAGGER):
    body.append(row(label, [pct(v) for v in vals]))
  return write(
      path,
      wrap(
          body,
          n_cols,
          "table*",
          r"\small",
          "2.1pt",
          CAPTIONS["prdb_full"],
          "tab:prdb_results_full",
      ),
  )


# LogReg vs XGBoost appendix tables (tab:head_comparison_prdb / _coling) from
# the cells frame: one row per (train_target, label, tau, head, split,
# generator) with the METRICS columns.
HC_METRICS = ["auroc", "f1", "recall_at_5_fpr"]
HC_TAU_BLOCKS = [
    ("0.0", r"\textbf{w/o Mask}"),
    ("0.7", r"\textbf{w/ Mask ($\tau\!>\!0.7$)}"),
]
HC_COLING_SPLITS = [
    ("COLING_dev", "COLING (dev)"),
    ("COLING_devtest", "COLING (devtest)"),
    ("COLING_test", "COLING (test)"),
    ("RAID_test", "RAID (test)"),
]
HC_PAIR_CAPTION = (
    "Each setting lists the LogReg head first and the XGBoost head on the "
    "indented line beneath it."
)


def hc_row_specs() -> list[tuple[str, str, str, str]]:
  """Every (block, label, head, tau) row in table order, LogReg first."""
  rows = [("Baselines", "gram2vec", h, "0.0") for h in ("logreg", "xgboost")]
  for tau, block in HC_TAU_BLOCKS:
    for sae in SAE_ORDER:
      rows += [(block, SAE_TEX[sae], h, tau) for h in ("logreg", "xgboost")]
  return rows


def hc_cell(df, label, tau, head, split, block, metric) -> float:
  """One metric from the cells frame; exactly one row must match."""
  sel = df[
      (df.label == label)
      & (df.tau == tau)
      & (df["head"] == head)
      & (df.split == split)
      & (df.generator == block)
  ]
  if len(sel) != 1:
    raise ValueError(
        f"{len(sel)} rows for {label} {tau} {head} {split} {block}"
    )
  return float(sel.iloc[0][metric])


def hc_rows(df, eval_cols, n_cols) -> list[str]:
  """Body lines for one training target: a LogReg row labelled with the
  setting, then an indented gray +XGBoost row, \\addlinespace between pairs."""
  lines, seen = [], []
  pad = " &" * (n_cols - 1) + r" \\"
  for block_name, label, head, tau in hc_row_specs():
    if block_name not in seen:
      if seen:
        lines.append(r"\midrule")
      seen.append(block_name)
      if block_name != "Baselines":
        lines.append(block_name + pad)
    elif head == "logreg":
      lines.append(r"\addlinespace")
    texts = [
        pct(hc_cell(df, label, tau, head, split, block, m))
        for split, block in eval_cols
        for m in HC_METRICS
    ]
    if head == "logreg":
      lines.append(f"{label} & " + " & ".join(texts) + r" \\")
    else:
      gray = [r"\textcolor{gray}{" + t + "}" for t in ["+XGBoost"] + texts]
      lines.append(r"\quad " + gray[0] + " & " + " & ".join(gray[1:]) + r" \\")
  return lines


def hc_header(groups: list[str], n_cols: int) -> list[str]:
  """Column-group header with cmidrules, then the metric header."""
  top = [r"\multicolumn{3}{c}{\textbf{" + g + "}}" for g in groups]
  rules = [
      rf"\cmidrule(lr){{{2 + 3 * i}-{4 + 3 * i}}}" for i in range(len(groups))
  ]
  return [
      rf"\begin{{tabular}}{{l{'c' * (n_cols - 1)}}}",
      r"\toprule",
      "& " + " & ".join(top) + r" \\",
      " ".join(rules),
      " & " + " & ".join(["AUC", "F1", "TPR@$5$"] * len(groups)) + r" \\",
      r"\midrule",
  ]


def hc_wrap(head, body, colsep, caption, label) -> str:
  lines = [
      r"\begin{table*}[t]",
      r"\centering",
      r"\small",
      rf"\setlength{{\tabcolsep}}{{{colsep}}}",
      r"\resizebox{\textwidth}{!}{%",
      *head,
      *body,
      r"\bottomrule",
      r"\end{tabular}}",
      rf"\caption{{{caption}}}",
      rf"\label{{{label}}}",
      r"\end{table*}",
  ]
  return "\n".join(lines) + "\n"


def head_comparison_prdb(frames: dict, path=None) -> str:
  """tab:head_comparison_prdb from {gpt4o: cells, llama: cells}, one half each."""
  generators = list(paper.GENERATOR_LABEL)
  n_cols = 1 + 3 * len(generators)
  body = []
  for i, (target, title) in enumerate(
      [("gpt4o", "Trained on GPT-4o"), ("llama", "Trained on LLaMA")]
  ):
    if i:
      body.append(r"\specialrule{\heavyrulewidth}{3pt}{3pt}")
    body.append(rf"\multicolumn{{{n_cols}}}{{l}}{{\textit{{{title}}}}} \\[2pt]")
    body += hc_rows(
        frames[target], [(f"PRDB_{target}", g) for g in generators], n_cols
    )
  caption = (
      r"Logistic-regression (LogReg) and XGBoost detector heads on the PRDB "
      r"test set, for detectors trained on GPT-4o- and LLaMA-generated text "
      r"respectively; each column group is text from a different source model. "
      + HC_PAIR_CAPTION
  )
  head = hc_header(list(paper.GENERATOR_LABEL.values()), n_cols)
  return write(
      path, hc_wrap(head, body, "2.1pt", caption, "tab:head_comparison_prdb")
  )


def head_comparison_coling(df, path=None) -> str:
  """tab:head_comparison_coling over the four held-out splits."""
  n_cols = 1 + 3 * len(HC_COLING_SPLITS)
  body = hc_rows(df, [(s, "all") for s, _ in HC_COLING_SPLITS], n_cols)
  caption = (
      r"Logistic-regression (LogReg) and XGBoost detector heads trained on the "
      r"COLING train set, evaluated on the held-out COLING and RAID splits. "
      + HC_PAIR_CAPTION
  )
  head = hc_header([s for _, s in HC_COLING_SPLITS], n_cols)
  return write(
      path, hc_wrap(head, body, "3.5pt", caption, "tab:head_comparison_coling")
  )


# tab:active_feature_counts from the global counts csv and the per-doc jsons.
COUNT_SETTINGS = [s for s in paper.SETTING_ORDER if not s.startswith("prdb_")]
COUNT_TAUS = ["0.0", "0.7", "0.85"]


def thousands(x) -> str:
  """Rounded integer with LaTeX-safe {,} thousands separators."""
  return f"{int(round(x)):,}".replace(",", "{,}")


def active_feature_counts(counts, per_doc, path, split="realtest") -> str:
  """Typeset the table and write active_per_doc_<split>.csv beside it.

  `counts` is the global step's csv (one row per group / sae_type), `per_doc`
  maps each COUNT_SETTINGS slug to its per-doc summary json (a dict).
  """
  n = len(COUNT_TAUS)
  rules = " ".join(
      rf"\cmidrule(lr){{{3 + n * i}-{2 + n * (i + 1)}}}" for i in range(3)
  )
  lines = [
      r"\begin{table*}[t]",
      r"\centering",
      r"\small",
      r"\setlength{\tabcolsep}{4pt}",
      r"\begin{tabular}{ll " + " ".join(["r" * n] * 3) + "}",
      r"\toprule",
      rf"& & \multicolumn{{{n}}}{{c}}{{\textbf{{Interpretable}}}} & \multicolumn{{{n}}}{{c}}"
      rf"{{\textbf{{Interp.\ \& $w>0$}}}} & \multicolumn{{{n}}}{{c}}{{\textbf{{Avg.\ \# active / doc}}}} \\",
      rules,
      r"\textbf{Data} & \textbf{SAE} & "
      + " & ".join(f"$\\tau\\!>\\!{t}$" for t in COUNT_TAUS * 3)
      + r" \\",
      r"\midrule",
  ]
  out_rows = []
  for slug in COUNT_SETTINGS:
    s = paper.SETTINGS[slug]
    group = paper.DATASET_NAME[s.dataset].lower()
    r = counts[(counts.group == group) & (counts.sae_type == s.sae)].iloc[0]
    js = per_doc[slug]
    summary = js["summary"]

    def count(t, suffix=""):
      return r[("Total" if float(t) == 0 else f"t>{t}") + suffix]

    act = [summary[f"{float(t):.2f}_wnz"]["mean"] for t in COUNT_TAUS]
    cells = (
        [paper.DATASET_NAME[s.dataset], SAE_TEX[s.sae]]
        + [thousands(count(t)) for t in COUNT_TAUS]
        + [thousands(count(t, " w>0")) for t in COUNT_TAUS]
        + [f"{x:.1f}" if x < 100 else thousands(x) for x in act]
    )
    lines.append(" & ".join(cells) + r" \\")
    out_rows.append(
        dict(
            group=group,
            sae_type=s.sae,
            split=split,
            n_docs=js["n_docs"],
            **{f"act/doc {k}": v["mean"] for k, v in summary.items()},
        )
    )
    if slug == "coling_ft_model_sae":
      lines.append(r"\midrule")
  split_txt = (
      "training document" if split == "train" else "held-out test document"
  )
  lines += [
      r"\bottomrule",
      r"\end{tabular}",
      r"\caption{SAE feature counts summed over the four probed layers. \textbf{Interpretable}: features whose auto-interp score exceeds $\tau$; $\tau\!>\!0.0$ is every feature with a description (the unmasked head). \textbf{Interp.\ \& $w>0$}: the subset of those that also receive a positive weight (toward the AI class) in the sparse (SGD+L1, $\lambda=10^{-1}$) logistic-regression head trained at that $\tau$. \textbf{Avg.\ \# active / doc}: mean number of nonzero-weight interpretable features that fire on a "
      + split_txt
      + r", i.e.\ that contribute a nonzero logit term to the prediction. PRDB rows use the GPT-4o target.}",
      r"\label{tab:active_feature_counts}",
      r"\end{table*}",
  ]
  out_dir = os.path.dirname(str(path)) or "."
  write(path, "\n".join(lines) + "\n")
  pd.DataFrame(out_rows).to_csv(
      f"{out_dir}/active_per_doc_{split}.csv", index=False
  )
  return "\n".join(lines) + "\n"


