"""Every LaTeX table of the paper, typeset byte for byte from frames and dicts.

Each emitter takes the data it typesets (a DataFrame, a dict of frames or a
worked-example record) and returns the LaTeX string; the ones that write
several files take an output directory. Nothing here reads eval or sweep
trees: analysis.ipynb loads the inputs and calls these.
"""

