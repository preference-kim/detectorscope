def top_rows(df, sign, n):
  """Top-n rows in one direction among features active in >= MIN_DOCS docs."""
  d = df[df.n_docs_active >= MIN_DOCS]
  d = d[d.mean_cf > 0] if sign > 0 else d[d.mean_cf < 0]
  return d.sort_values("mean_cf", ascending=(sign < 0)).head(n)


def dump_path(out_dir, setting) -> str:
  return f"{out_dir}/all_features_{paper.DATASET_NAME[setting.dataset].lower()}_{setting.train_dir}_{setting.target}_tau{TAU}.csv"


def top_features_dump(df, setting, out_dir) -> str:
  """Write the per-condition dump of one setting's feature frame."""
  block = DUMP_BLOCK.get(setting.key, setting.tex_label)
  path = dump_path(out_dir, setting)
  table = paper.DATASET_NAME[setting.dataset].lower()
  df[DUMP_COLS].assign(block=block, table=table).to_csv(path, index=False)
