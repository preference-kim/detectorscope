  f1 = df.pivot(index="setting", columns="cond", values="f1").reindex(settings)[
      conds
  ]
  wlev = (
      df[df.cond != "base"]
      .pivot(index="setting", columns="cond", values="wlev")
      .reindex(settings)
  )
  with pd.option_context("display.width", 250):
    return (
        "F1:\n"
        + f1.to_string(float_format=lambda v: f"{v:.3f}")
        + "\nwLev:\n"
        + wlev.to_string(float_format=lambda v: f"{100 * v:.1f}")
    )


